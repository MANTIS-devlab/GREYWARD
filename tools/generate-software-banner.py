#!/usr/bin/env python3
"""Generate the self-contained Bazaar banner from canonical GREYWARD artwork."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = 'http://www.w3.org/2000/svg'
ET.register_namespace('', NS)


def generate():
    palette = json.loads((ROOT / 'branding/identity.json').read_text())['palette']
    # The installed curated row is 220px high. Keep all meaningful content
    # inside the central 560px so Gtk.Picture's cover crop remains legible
    # in narrow windows as well as at the full banner width.
    banner = ET.fromstring(f'''<svg xmlns="{NS}" width="1600" height="220"
      viewBox="0 0 1600 220" role="img" aria-labelledby="software-title software-desc">
      <title id="software-title">GREYWARD Software</title>
      <desc id="software-desc">The GREYWARD emblem on an obsidian Software banner.</desc>
      <defs>
        <linearGradient id="software-surface" x1="0" y1="0" x2="1" y2="0">
          <stop offset="0" stop-color="{palette['obsidian']}"/>
          <stop offset="0.5" stop-color="{palette['charcoal']}"/>
          <stop offset="1" stop-color="{palette['obsidian']}"/>
        </linearGradient>
      </defs>
      <rect width="1600" height="220" fill="url(#software-surface)"/>
      <path d="M700 68v84" stroke="{palette['graphite']}" stroke-opacity="0.55"/>
      <g fill="{palette['silver']}" font-family="Noto Sans, sans-serif">
        <text x="732" y="111" font-size="42" font-weight="600" letter-spacing="3">GREYWARD</text>
        <text x="735" y="143" font-size="12" font-weight="500" letter-spacing="5" fill="{palette['muted']}">SOFTWARE</text>
      </g>
    </svg>''')
    symbol = ET.parse(ROOT / 'branding/source/greyward-symbol.svg').getroot()
    emblem = ET.SubElement(banner, f'{{{NS}}}svg', {
        'x': '550', 'y': '28', 'width': '132', 'height': '164',
        'viewBox': '220 180 600 680', 'preserveAspectRatio': 'xMidYMid meet'})
    for child in symbol:
        if child.tag != f'{{{NS}}}metadata':
            emblem.append(child)
    ET.indent(banner, space='  ')
    output = ROOT / 'environment/flatpak/greyward-software-banner.svg'
    output.write_text('<!-- Generated by tools/generate-software-banner.py; do not edit by hand. -->\n'
                      + ET.tostring(banner, encoding='unicode') + '\n',
                      encoding='utf-8', newline='\n')
    print(output)


if __name__ == '__main__':
    generate()
